#!/usr/bin/env python3
"""Generate port/loader/d3d9_model_gen.h: forwarding classes for IDirect3D9 and IDirect3DDevice9 (Phase 2, the
Direct3D 9 model; docs/PHASE2_PLAN.md section 2).

The model is our own implementation of the interfaces the game calls. This first layer forwards every method to the
real d3d9.dll object and gives each state-changing method a recording hook (`model_<Method>` in
port/loader/d3d9_model.h, called before forwarding), so state, resources and frames can be kept in our own objects;
Phase 4 replaces the forwarding with a WebGPU backend in the same place. The method lists come from the Windows
SDK's d3d9.h, so vtable order is exactly the runtime's.

usage: python tools/gen_d3d9_model.py  (writes port/loader/d3d9_model_gen.h)
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = Path(r'C:/Program Files (x86)/Windows Kits/10/Include/10.0.22621.0/shared/d3d9.h')
# device methods whose arguments the model records before forwarding (hooks in d3d9_model.h)
HOOKED = {'Present', 'BeginScene', 'EndScene', 'Clear', 'SetRenderTarget', 'SetDepthStencilSurface', 'SetViewport',
          'SetRenderState', 'SetSamplerState', 'SetTexture', 'SetVertexShader', 'SetPixelShader',
          'SetVertexShaderConstantF', 'SetPixelShaderConstantF', 'SetStreamSource', 'SetIndices',
          'SetVertexDeclaration', 'SetFVF', 'SetScissorRect', 'StretchRect', 'DrawPrimitive', 'DrawIndexedPrimitive',
          'DrawPrimitiveUP', 'DrawIndexedPrimitiveUP', 'CreateTexture', 'CreateVertexBuffer', 'CreateIndexBuffer',
          'CreateRenderTarget', 'CreateDepthStencilSurface', 'CreateVertexShader', 'CreatePixelShader', 'Reset'}


def methods(text, iface):
    m = re.search(r'DECLARE_INTERFACE_\(%s, IUnknown\)\s*\{(.*?)\n\}' % iface, text, re.S)
    out = []
    for line in m.group(1).splitlines():
        line = line.strip()
        mm = re.match(r'STDMETHOD(?:_\(\s*([^,]+?)\s*,\s*(\w+)\)|\((\w+)\))\s*\(THIS_?\s*(.*?)\)\s*PURE;', line)
        if not mm:
            continue
        ret = mm.group(1) or 'HRESULT'
        name = mm.group(2) or mm.group(3)
        params = mm.group(4).strip()
        plist = [p.strip() for p in params.split(',')] if params else []
        names = []
        for i, p in enumerate(plist):
            # unnamed parameters (`D3DLIGHT9*`, `D3DPRIMITIVETYPE`): give them a name
            if p.endswith('*') or len(p.replace('CONST ', '').split()) == 1:
                plist[i] = p + ' a%d' % i
                names.append('a%d' % i)
                continue
            nm = re.findall(r'(\w+)\s*(?:\[[^\]]*\])?$', p)
            names.append(nm[0] if nm else 'a%d' % i)
        out.append((ret, name, plist, names))
    return out


def emit_class(cls, iface, ms, hooked):
    lines = ['struct %s : public %s' % (cls, iface), '{', '    %s* real;' % iface, '    LONG refs = 1;',
             '    explicit %s(%s* r) : real(r) {}' % (cls, iface)]
    for ret, name, plist, names in ms:
        params = ', '.join(plist)
        args = ', '.join(names)
        body = []
        if name == 'AddRef':
            body = ['InterlockedIncrement(&refs);', 'return real->AddRef();']
        elif name == 'Release':
            body = ['ULONG r = real->Release();', 'if (!InterlockedDecrement(&refs)) delete this;', 'return r;']
        elif name == 'QueryInterface':
            body = ['if (riid == __uuidof(%s) || riid == __uuidof(IUnknown)) { *ppvObj = this; AddRef(); return S_OK; }'
                    % iface, 'return real->QueryInterface(riid, ppvObj);']
        else:
            if name in hooked:
                body.append('model_%s(this%s);' % (name, ', ' + args if args else ''))
            call = 'real->%s(%s)' % (name, args)
            body.append(('return %s;' % call) if ret != 'void' else '%s;' % call)
        lines.append('    %s STDMETHODCALLTYPE %s(%s) override { %s }' % (ret, name, params, ' '.join(body)))
    lines.append('};')
    return lines


def main():
    text = HEADER.read_text(errors='replace')
    dev = methods(text, 'IDirect3DDevice9')
    d3d = methods(text, 'IDirect3D9')
    assert len(dev) == 119 and len(d3d) == 17, (len(dev), len(d3d))
    out = ['// Generated by tools/gen_d3d9_model.py from the Windows SDK d3d9.h: do not edit.',
           '// Forwarding layer of the Direct3D 9 model; the model_* hooks live in d3d9_model.h.', '#pragma once', '']
    out += ['struct FnvDevice9;']
    for ret, name, plist, names in dev:
        if name in HOOKED:
            params = ', '.join(['FnvDevice9* dev'] + plist)
            out.append('static void model_%s(%s);' % (name, params))
    out.append('')
    out += emit_class('FnvDevice9', 'IDirect3DDevice9', dev, HOOKED)
    out.append('')
    d3d_lines = emit_class('FnvDirect3D9', 'IDirect3D9', d3d, set())
    # CreateDevice returns the model's device around the real one
    d3d_lines = [l if ' CreateDevice(' not in l else
                 '    HRESULT STDMETHODCALLTYPE CreateDevice(UINT Adapter, D3DDEVTYPE DeviceType, HWND hFocusWindow, '
                 'DWORD BehaviorFlags, D3DPRESENT_PARAMETERS* pPresentationParameters, '
                 'IDirect3DDevice9** ppReturnedDeviceInterface) override { HRESULT hr = real->CreateDevice(Adapter, '
                 'DeviceType, hFocusWindow, BehaviorFlags, pPresentationParameters, ppReturnedDeviceInterface); '
                 'if (hr >= 0 && ppReturnedDeviceInterface && *ppReturnedDeviceInterface) *ppReturnedDeviceInterface = '
                 'model_wrap_device(*ppReturnedDeviceInterface, pPresentationParameters); return hr; }'
                 for l in d3d_lines]
    out += ['static IDirect3DDevice9* model_wrap_device(IDirect3DDevice9* real, D3DPRESENT_PARAMETERS* pp);', '']
    out += d3d_lines
    (ROOT / 'port/loader/d3d9_model_gen.h').write_text('\n'.join(out) + '\n')
    print('IDirect3DDevice9: %d methods (%d hooked), IDirect3D9: %d methods' % (len(dev), len(HOOKED & {m[1] for m in dev}), len(d3d)))


if __name__ == '__main__':
    main()
