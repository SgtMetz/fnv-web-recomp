#!/usr/bin/env python3
"""Method tables (vtable order, argument bytes) of the COM interfaces the game uses, from the Windows SDK headers, for
the recompiler's PAL COM layer (port/recomp/pal_com.cpp). Every method is stdcall with `this` first; the SDK headers
spell out each interface's full method list (inherited methods included), so the order is the runtime's.

Output: out/recomp/com_tables.inc (derived from SDK headers, git-ignored):
  static const ComMethod kCom_<Iface>[] = {{"QueryInterface", 12}, ...};
  {"<Iface>", kCom_<Iface>, N},   (in the kComInterfaces list at the end)

usage: python tools/gen_com_tables.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INC = sorted(Path(r'C:/Program Files (x86)/Windows Kits/10/Include').iterdir())[-1]
HEADERS = {
    'shared/d3d9.h': ['IDirect3D9', 'IDirect3DDevice9', 'IDirect3DSwapChain9', 'IDirect3DResource9',
                      'IDirect3DVertexDeclaration9', 'IDirect3DVertexShader9', 'IDirect3DPixelShader9',
                      'IDirect3DBaseTexture9', 'IDirect3DTexture9', 'IDirect3DVolumeTexture9', 'IDirect3DCubeTexture9',
                      'IDirect3DVertexBuffer9', 'IDirect3DIndexBuffer9', 'IDirect3DSurface9', 'IDirect3DVolume9',
                      'IDirect3DQuery9', 'IDirect3DStateBlock9'],
    'um/dinput.h': ['IDirectInput8A', 'IDirectInputDevice8A'],
    'um/dsound.h': ['IDirectSound8', 'IDirectSoundBuffer', 'IDirectSoundBuffer8', 'IDirectSound3DListener',
                    'IDirectSound3DBuffer', 'IDirectSoundNotify'],
}
# by-value parameters wider than 4 bytes (none expected in these interfaces; checked)
WIDE = re.compile(r'\b(double|DOUBLE|LONGLONG|ULONGLONG|D3DMATRIX\s+\w+$|LARGE_INTEGER\s+\w+$)\b')


def methods(text, iface):
    m = re.search(r'DECLARE_INTERFACE_\(\s*%s\s*,\s*\w+\s*\)\s*\{(.*?)\n\}' % iface, text, re.S)
    if not m:
        raise SystemExit('interface %s not found' % iface)
    body = re.sub(r'/\*.*?\*/', '', m.group(1), flags=re.S)
    body = re.sub(r'\s+', ' ', body)
    out = []
    for mm in re.finditer(r'STDMETHOD(?:_\(\s*([^,]+?)\s*,\s*(\w+)\s*\)|\(\s*(\w+)\s*\))\s*\(\s*THIS_?\s*(.*?)\)\s*PURE\s*;',
                          body):
        name = mm.group(2) or mm.group(3)
        params = [p.strip() for p in mm.group(4).split(',') if p.strip() and p.strip() != 'void']
        for p in params:
            if WIDE.search(p):
                raise SystemExit('%s::%s has a wide by-value parameter: %s' % (iface, name, p))
        out.append((name, 4 * (1 + len(params))))   # this + parameters
    return out


def main():
    lines = ['// Generated by tools/gen_com_tables.py from the Windows SDK headers: do not edit or commit.']
    listing = []
    for header, ifaces in HEADERS.items():
        text = (INC / header).read_text(errors='replace')
        for iface in ifaces:
            ms = methods(text, iface)
            lines.append('static const ComMethod kCom_%s[] = {%s};' % (
                iface, ', '.join('{"%s", %d}' % m for m in ms)))
            listing.append('{"%s", kCom_%s, %d},' % (iface, iface, len(ms)))
    lines.append('static const ComInterface kComInterfaces[] = {')
    lines += ['    ' + l for l in listing]
    lines.append('};')
    out = ROOT / 'out/recomp/com_tables.inc'
    out.write_text('\n'.join(lines) + '\n')
    print('%d interfaces -> %s' % (len(listing), out))


if __name__ == '__main__':
    main()
