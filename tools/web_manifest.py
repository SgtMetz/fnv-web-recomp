"""Write web/src/manifest.json: the install files the browser importer expects, grouped for "lite" imports.

The manifest holds file names and byte sizes of the reference install (GOG 1.4.0.525) only, no file contents. The
importer uses it to check a player's install before copying it into the browser's origin-private file system (OPFS).
Sizes that differ are reported as warnings, since other editions and languages ship different builds of some files.

Usage: python tools/web_manifest.py --install "E:\\Games\\Fallout New Vegas" [--out web/src/manifest.json]
"""
import argparse
import json
import os
from pathlib import Path

# (group id, label, required, default-selected, members). Members are paths relative to the install root; a trailing
# "/" means "every file below this folder" (checked by count and total size, not file by file).
DLC = [
    ("deadmoney", "Dead Money", "DeadMoney", ["DeadMoney.esm", "DEADMONEY.NAM", "DeadMoney - Main.bsa", "DeadMoney - Sounds.bsa"]),
    ("honesthearts", "Honest Hearts", "HonestHearts", ["HonestHearts.esm", "HONESTHEARTS.NAM", "HonestHearts - Main.bsa", "HonestHearts - Sounds.bsa"]),
    ("oldworldblues", "Old World Blues", "OldWorldBlues", ["OldWorldBlues.esm", "OLDWORLDBLUES.NAM", "OldWorldBlues - Main.bsa", "OldWorldBlues - Sounds.bsa"]),
    ("lonesomeroad", "Lonesome Road", "LonesomeRoad", ["LonesomeRoad.esm", "LONESOMEROAD.NAM", "LonesomeRoad - Main.bsa", "LonesomeRoad - Sounds.bsa"]),
    ("gunrunners", "Gun Runners' Arsenal", "GunRunnersArsenal", ["GunRunnersArsenal.esm", "GUNRUNNERSARSENAL.NAM", "GunRunnersArsenal - Main.bsa", "GunRunnersArsenal - Sounds.bsa"]),
    ("caravanpack", "Courier's Stash: Caravan Pack", "CaravanPack", ["CaravanPack.esm", "CaravanPack.nam", "CaravanPack - Main.bsa"]),
    ("classicpack", "Courier's Stash: Classic Pack", "ClassicPack", ["ClassicPack.esm", "ClassicPack.nam", "ClassicPack - Main.bsa"]),
    ("mercenarypack", "Courier's Stash: Mercenary Pack", "MercenaryPack", ["MercenaryPack.esm", "MercenaryPack.nam", "MercenaryPack - Main.bsa"]),
    ("tribalpack", "Courier's Stash: Tribal Pack", "TribalPack", ["TribalPack.esm", "TribalPack.nam", "TribalPack - Main.bsa"]),
]

GROUPS = [
    ("core", "Base game", True, True, [
        "Data/FalloutNV.esm", "Data/Fallout - Meshes.bsa", "Data/Fallout - Textures.bsa", "Data/Fallout - Textures2.bsa",
        "Data/Fallout - Sound.bsa", "Data/Fallout - Misc.bsa", "Data/Update.bsa", "Fallout_default.ini"]),
    # Optional parts of the base game: present in the reference install, not needed to start a game.
    ("extras", "Language plugin, credits and launcher presets", False, True, [
        "Data/FalloutNV_lang.esp", "Data/Credits.txt", "Data/CreditsWacky.txt",
        "low.ini", "medium.ini", "high.ini", "VeryHigh.ini"]),
    ("shaders", "Shader packages", True, True, ["Data/Shaders/"]),
    ("voices", "Voices", False, True, ["Data/Fallout - Voices1.bsa"]),
    ("music", "Music", False, True, ["Data/Music/"]),
    ("radio", "Radio and loose sound", False, True, ["Data/Sound/"]),
    ("video", "Intro video", False, False, ["Data/Video/"]),
]


def describe(root: Path, member: str):
    if member.endswith("/"):
        d = root / member
        files = [p for p in d.rglob("*") if p.is_file()] if d.is_dir() else []
        return {"dir": member, "files": len(files), "bytes": sum(p.stat().st_size for p in files)}
    p = root / member
    if not p.is_file():
        raise SystemExit(f"missing from the reference install: {member}")
    return {"path": member, "size": p.stat().st_size}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--install", required=True)
    ap.add_argument("--out", default=str(Path(__file__).resolve().parent.parent / "web" / "src" / "manifest.json"))
    a = ap.parse_args()
    root = Path(a.install)
    groups = []
    for gid, label, required, selected, members in GROUPS:
        groups.append({"id": gid, "label": label, "required": required, "selected": selected,
                       "members": [describe(root, m) for m in members]})
    for gid, label, plugin, members in DLC:
        groups.append({"id": gid, "label": label, "required": False, "selected": True, "dlc": True,
                       "plugin": plugin + ".esm", "members": [describe(root, "Data/" + m) for m in members]})
    out = {
        "format": 1,
        "edition": "GOG Ultimate Edition, FalloutNV.exe 1.4.0.525",
        "note": "Names and sizes only. Generated by tools/web_manifest.py from the reference install.",
        "groups": groups,
    }
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8")
    total = sum(m.get("size", m.get("bytes", 0)) for g in groups for m in g["members"])
    print(f"wrote {a.out}: {len(groups)} groups, {total / 2**30:.2f} GiB")


if __name__ == "__main__":
    main()
